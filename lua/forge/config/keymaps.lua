-- Global keymaps: the complete landmark set, plus tests, tasks,
-- refactoring, search/replace, outline and inline AI.
local map = vim.keymap.set
local function cmd(c) return "<Cmd>" .. c .. "<CR>" end

-- Window / buffer basics
map("n", "<C-h>", "<C-w>h", { desc = "Focus left window" })
map("n", "<C-j>", "<C-w>j", { desc = "Focus lower window" })
map("n", "<C-k>", "<C-w>k", { desc = "Focus upper window" })
map("n", "<C-l>", "<C-w>l", { desc = "Focus right window" })
map("n", "<S-h>", cmd("bprevious"), { desc = "Previous buffer" })
map("n", "<S-l>", cmd("bnext"), { desc = "Next buffer" })
map("n", "<leader>bd", cmd("lua require('forge.util').bufdelete()"), { desc = "Delete buffer" })
map("n", "<Esc>", cmd("nohlsearch"), { desc = "Clear search highlight" })
map({ "i", "n" }, "<C-s>", cmd("write"), { desc = "Save file" })
map("v", "<", "<gv"); map("v", ">", ">gv")
map("n", "j", "v:count == 0 ? 'gj' : 'j'", { expr = true, silent = true })
map("n", "k", "v:count == 0 ? 'gk' : 'k'", { expr = true, silent = true })
map("x", "p", '"_dP', { desc = "Paste without yanking replaced text" })

-- Files / search (fzf-lua is primary like the original; Telescope also loaded)
map("n", "<C-p>", cmd("lua require('forge.palette').files()"), { desc = "Find project files" })
map("n", "<C-f>", cmd("lua require('forge.palette').grep()"), { desc = "Search project text" })
map("n", "<leader>ff", cmd("lua require('forge.palette').files()"), { desc = "Find files" })
map("n", "<leader>fg", cmd("lua require('forge.palette').grep()"), { desc = "Live grep" })
